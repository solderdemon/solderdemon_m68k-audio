#!/usr/bin/env python3
"""Generate the public-domain score and demo documentation; edit this source."""
from pathlib import Path
OUT = Path(__file__).resolve().parents[1] / 'code/software/music_demo'
# Traditional Korobeiniki melody, in an original three-voice arrangement.
# Eight eighth-notes per bar, 20 timer ticks per eighth (150 BPM).
BARS = [
 'E5:2 B4:1 C5:1 D5:2 C5:1 B4:1',
 'A4:2 A4:1 C5:1 E5:2 D5:1 C5:1',
 'B4:3 C5:1 D5:2 E5:2', 'C5:2 A4:2 A4:4',
 'D5:3 F5:1 A5:2 G5:1 F5:1',
 'E5:3 C5:1 E5:2 D5:1 C5:1',
 'B4:2 B4:1 C5:1 D5:2 E5:2', 'C5:2 A4:2 A4:4',
]
CHORDS = [1,0,1,0,2,0,1,0]
def midi(name):
 return (int(name[-1])+1)*12 + {'C':0,'D':2,'E':4,'F':5,'G':7,'A':9,'B':11}[name[0]]
def main():
 readme = OUT.parents[2] / 'README.md'
 text = readme.read_bytes()
 newline = b'\r\n' if b'\r\n' in text else b'\n'
 section = '<!-- music-demo -->\n### Musical demo: Korobeiniki (Tetris theme)\n\n[`code/software/music_demo`](code/software/music_demo/README.md) contains a 30-second original\nchiptune arrangement of the traditional Korobeiniki melody, familiar from Tetris.\nIt builds from solo to bass, arpeggios, stereo voice swap, and noise percussion.\nBuild with `rosco build --docker`; instructions and a WAV preview are included.\n<!-- /music-demo -->\n'.encode().replace(b'\n', newline)
 start_marker = b'<!-- music-demo -->'
 end_marker = b'<!-- /music-demo -->'
 if start_marker in text:
  start = text.index(start_marker)
  end = text.index(end_marker, start) + len(end_marker) + len(newline)
  text = text[:start] + section + text[end:]
 else:
  anchor = b'## Build and verification'
  assert anchor in text
  text = text.replace(anchor, section + newline + anchor, 1)
 readme.write_bytes(text)
 (OUT/'solderdemon_audio.h').write_text(
  '/* Generated copy of ../solderdemon_audio.h for the Docker build context. */\n'+
  (OUT.parent/'solderdemon_audio.h').read_text())
 events=[]
 for bar in BARS:
  notes=[s.split(':') for s in bar.split()]
  assert sum(int(d) for _,d in notes)==8
  events.extend((midi(n),int(d)*20) for n,d in notes)
 assert sum(d for _,d in events)==1280
 periods=[round(1843200/(16*440*2**((n-69)/12))) for n in range(36,85)]
 (OUT/'score.h').write_text(
  '/* Generated by tools/generate_music_demo.py. */\n#ifndef MUSIC_SCORE_H\n#define MUSIC_SCORE_H\n'
  '#define MUSIC_THEME_TICKS 1280u\n#define MUSIC_TOTAL_TICKS 3000u\n'
  'struct music_note { unsigned char midi; unsigned char ticks; };\n'
  'static const struct music_note melody[] = {\n'+
  ''.join(f' {{{n}, {d}}},\n' for n,d in events)+'};\n'
  'static const unsigned short periods[] = {'+', '.join(map(str,periods))+'};\n'
  'static const unsigned char chords[8] = {'+', '.join(map(str,CHORDS))+'};\n#endif\n')
 (OUT/'README.md').write_text('''# Korobeiniki — m68k PSG trailer

30-second original chiptune arrangement of the traditional Korobeiniki melody,
familiar from Tetris, at 150 BPM for the SolderDemon m68k YM2149 card
(1.8432 MHz PSG clock). This is a new score, not a game audio recording.

0–3.2 s: melody solo on A (left). 3.2–6.4 s: centered bass enters on B.
6.4–12.8 s: plucked arpeggios enter on C (right). 12.8–25.6 s:
melody swaps to C, with vibrato and alternating arpeggios/noise drums on A.
25.6–30 s: A-minor final chord decays to silence. Plucks and drums use the
shared falling hardware envelope (shape 9); melody and bass have independent
software dynamics.

## Build and play

From this directory, with rosco CLI and Docker running:

```sh
python3 ../../../tools/generate_music_demo.py
rosco build --docker
rosco run --port /dev/ttyUSB0
```

The output is `music_demo.bin`, with ELF, map, and disassembly alongside it.
Use `rosco ports` to find your UART port. This uses rosco's serial startup and
linker script: load it through the firmware, unlike the raw subroutine in
`../demo`. Press any key to stop. Playback also ends automatically after 30 s.
All channels are muted before returning to the starter runtime, which reboots
back to firmware.

Supervisor mode and the firmware's 100 Hz timer interrupt must be enabled.
Playback follows `_TIMER_100HZ`, so CPU speed does not change the tempo. Late
frames are skipped. The player exclusively owns the PSG while running. The
existing `solderdemon_audio.h` driver makes atomic register/data byte writes at
$F00101/$F00103, restoring the interrupt mask after each pair. Registers 14/15
are never used. Connect powered speakers or an amplifier line input to J2/J3;
start with low amplifier volume (this is a passive line output).

## Edit and verify

Edit the score in `../../../tools/generate_music_demo.py` and regenerate. Edit
`player.c` for instrumentation and `kmain.c` for firmware playback.
Run `python3 ../../../tools/verify_music_demo.py` to check the actual C renderer
and generate an approximate stereo `music_demo-preview.wav`. The preview is
not a measurement of the board or its exact analog/DAC response.

Starter files/libraries were created with `rosco init --board rosco_m68k
--language c --docker --target hardware --yes`. Code is MIT as in the parent
card project; bundled rosco libraries retain their original licenses.
''')
if __name__=='__main__': main()
